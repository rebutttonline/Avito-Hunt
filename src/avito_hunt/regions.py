REGION_NEIGHBORS: dict[str, tuple[str, ...]] = {
    "москва": ("московская область", "тверь", "тула", "калуга", "рязань"),
    "санкт-петербург": ("ленинградская область", "великий новгород", "псков"),
    "казань": ("набережные челны", "ижевск", "ульяновск", "чебоксары"),
    "екатеринбург": ("челябинск", "пермь", "тюмень", "курган"),
    "новосибирск": ("томск", "кемерово", "барнаул", "новокузнецк"),
}


def nearby_regions(region: str) -> tuple[str, ...]:
    normalized = region.casefold().strip()
    return (normalized, *REGION_NEIGHBORS.get(normalized, ()))
